// Verification: Prova dei tipi del database generati
import { readdirSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { expect, test } from 'vitest';
import { repositoryRoot } from './source-imports.js';

// «Tipi del database con kysely-codegen»: the static part of the proof. `pnpm db:types:check`, run by the CI on a
// database built with the migrations, compares the versioned file with the migrated schema.
const postgres = 'packages/conversations/src/adapters/out/postgres';
const generated = `${postgres}/database.generated.ts`;
const text = (file: string) => readFileSync(join(repositoryRoot, file), 'utf8');
const specifiers = (source: string) => [...source.matchAll(/\b(?:import|export)\b[^'"]*?\bfrom\s*['"]([^'"]+)['"]|\bimport\s*\(\s*['"]([^'"]+)['"]\s*\)/g)]
  .map((match) => match[1] ?? match[2]!);

test('the versioned configuration declares the dialect, the parsers, the tables and the output file', () => {
  expect(JSON.parse(text('.kysely-codegenrc.json'))).toEqual({
    dialect: 'postgres', dateParser: 'timestamp', numericParser: 'string',
    includePattern: 'public.+(conversations|turns)', outFile: generated,
  });
});

test('the scripts regenerate and verify the types after the build with the database types script', () => {
  const manifest = JSON.parse(text('package.json')) as { scripts: Record<string, string>; devDependencies: Record<string, string> };
  expect(manifest.scripts['db:types']).toBe('node scripts/database-types.mjs');
  expect(manifest.scripts['db:types:check']).toBe('node scripts/database-types.mjs --verify');
  expect(manifest.devDependencies['kysely-codegen']).toMatch(/^\d+\.\d+\.\d+$/);
  expect(manifest.scripts.verify).toMatch(/pnpm build && pnpm db:types:check && pnpm typecheck/);
  const script = text('scripts/database-types.mjs');
  expect(script).toContain("dist/adapters/out/postgres/temporary-database.js");
  expect(script).toMatch(/createMigratedTemporaryDatabase\(serverUrl\)/);
  expect(script).toMatch(/'--verify'/);
  // The database is dropped also when kysely-codegen fails.
  expect(script).toMatch(/try \{[\s\S]*kysely-codegen[\s\S]*\} finally \{\s*await database\.drop\(\);\s*\}/);
});

test('the generated file holds only type declarations and imports no Domain or Application code', () => {
  const source = text(generated);
  expect(source).toMatch(/This file was generated by kysely-codegen/);
  expect(specifiers(source)).toEqual(['kysely']);
  expect(source).toMatch(/^import type \{ ColumnType \} from "kysely";$/m);
  const statements = source.replace(/\/\*[\s\S]*?\*\//g, '').split('\n').filter((line) => /^\S/.test(line));
  for (const line of statements) expect(line).toMatch(/^(import type |export type |export interface |\}|\};)/);
  expect(source).toMatch(/export interface DB \{\s*conversations: Conversations;\s*turns: Turns;\s*\}/);
});

test('only the adapters of postgres/ import the generated types, and the migrations never do', () => {
  const roots = ['packages', 'apps', 'test', 'scripts'];
  const files = roots.flatMap((top) => readdirSync(join(repositoryRoot, top), { recursive: true, encoding: 'utf8' })
    .filter((name) => /\.(ts|mjs)$/.test(name) && !/(^|\/)(node_modules|dist)\//.test(name))
    .map((name) => join(top, name)));
  const importers = files.filter((file) => specifiers(text(file))
    .some((specifier) => specifier.startsWith('.') && join(dirname(file), specifier) === `${postgres}/database.generated.js`));
  expect(importers.length).toBeGreaterThan(0);
  for (const file of importers) expect(dirname(file), file).toBe(postgres);
  for (const file of readdirSync(join(repositoryRoot, postgres, 'migrations')).filter((name) => name.endsWith('.ts'))) {
    expect(specifiers(text(`${postgres}/migrations/${file}`)), file).not.toContain('../database.generated.js');
  }
  expect(specifiers(text(`${postgres}/migrations.ts`))).not.toContain('./database.generated.js');
});
